"""High-Level Color & Linearization Engine for Canon G640.

Implements:
1. Calibration Target Mode (Raw 1:1 Passthrough for ArgyllCMS targen/printtarg)
2. Production Mode (LittleCMS2 16-bit ICC + RelCol + BPC + 1D LUT Linearization + Total Ink Limit)
"""

import os
from typing import Optional, Tuple, Union
import numpy as np
from PIL import Image

from .ink_limit import InkLimiter
from .lcms2_capi import (
    LCMS2Profile,
    LCMS2Transform,
    TYPE_RGB_8,
    TYPE_RGB_16,
    INTENT_RELATIVE_COLORIMETRIC,
    INTENT_PERCEPTUAL,
    cmsFLAGS_BLACKPOINTCOMPENSATION,
    cmsFLAGS_HIGHRESPRECALC,
)
from .linearization import LinearizationLUT
from ..transport.constants import PAPER_SIZES, get_paper_spec


class ColorEngine:
    """Core color processing pipeline for Canon G640 micro-RIP."""

    def __init__(
        self,
        paper_profile_path: Optional[str] = None,
        input_profile_path: Optional[str] = None,
        linearization: Optional[LinearizationLUT] = None,
        ink_limiter: Optional[InkLimiter] = None,
        contrast: float = 0.0,
        intent: int = INTENT_RELATIVE_COLORIMETRIC,
        use_bpc: bool = True,
    ):
        self.paper_profile_path = paper_profile_path
        self.input_profile_path = input_profile_path
        self.linearization = linearization or LinearizationLUT.create_identity()
        self.ink_limiter = ink_limiter or InkLimiter(max_total_ink=1.0)
        self.contrast = float(contrast)
        self.intent = intent
        self.use_bpc = use_bpc

        self._paper_profile: Optional[LCMS2Profile] = None
        self._input_profile: Optional[LCMS2Profile] = None

        if paper_profile_path and os.path.exists(paper_profile_path):
            self._paper_profile = LCMS2Profile.open_file(paper_profile_path)

        if input_profile_path and os.path.exists(input_profile_path):
            self._input_profile = LCMS2Profile.open_file(input_profile_path)

    # -------------------------------------------------------------
    # 1. Calibration Target Mode (ArgyllCMS Raw Passthrough)
    # -------------------------------------------------------------
    def process_calibration_target(
        self,
        target_image: Image.Image,
        page_size_name: str = "A4",
        dpi: int = 600,
        center_on_page: bool = True,
    ) -> Image.Image:
        """
        Mode 1: Calibration Target Mode.
        CRITICAL: Completely bypasses ICC profiles, ColorSync, and curves.
        Guarantees that RGB/CMYK patches generated by ArgyllCMS targen/printtarg
        are placed onto the 600 DPI canvas without ANY pixel interpolation,
        resampling, or color shifts.
        """
        # Ensure 8-bit RGB or convert cleanly without color management
        if target_image.mode != "RGB":
            target_image = target_image.convert("RGB")

        orig_w, orig_h = target_image.size
        target_arr = np.array(target_image, dtype=np.uint8)

        # Get canvas size
        page_spec = PAPER_SIZES.get(page_size_name, PAPER_SIZES["A4"])
        canvas_w = page_spec["width_600dpi"]
        canvas_h = page_spec["height_600dpi"]

        # If target already matches or exceeds canvas, do not resize patches
        if orig_w > canvas_w or orig_h > canvas_h:
            # Scale canvas up to target size so no patches are lost or resampled
            canvas_w = max(canvas_w, orig_w)
            canvas_h = max(canvas_h, orig_h)

        # Create pure white background (255, 255, 255)
        canvas = np.full((canvas_h, canvas_w, 3), 255, dtype=np.uint8)

        if center_on_page:
            offset_x = (canvas_w - orig_w) // 2
            offset_y = (canvas_h - orig_h) // 2
        else:
            offset_x = 0
            offset_y = 0

        # Direct 1:1 pixel copy - ZERO interpolation
        canvas[offset_y : offset_y + orig_h, offset_x : offset_x + orig_w] = target_arr

        return Image.fromarray(canvas, mode="RGB")

    # -------------------------------------------------------------
    # 2. Production Mode (16-bit ICC + Linearization + Ink Limit)
    # -------------------------------------------------------------
    @staticmethod
    def prepare_image_layout(
        image: Image.Image,
        page_size_name: str = "10x15",
        borderless: bool = True,
        fit_mode: str = "compensate",  # "compensate" (100% safe area + edge buffer), "fill" (crop), "fit" (contain), "none"
        bleed_pct: float = 0.0,
        comp_x_pct: float = 0.0,
        comp_y_pct: float = 5.0,
        offset_x_pct: float = 0.0,
        offset_y_pct: float = 0.0,
        scale_x_pct: float = 0.0,
        scale_y_pct: float = 0.0,
        auto_rotate: bool = True,
        dpi: int = 600,
    ) -> Image.Image:
        """
        Scale, auto-orient, and frame input image to exact target canvas dimensions at specified DPI.

        Framing Modes:
        - "compensate": Hardware Bleed Compensation. Scales image so real photo content covers
          100% of the width (no repeated pixels on right/left) while keeping the vertical safe area
          protected (preventing bottom cut-off).
        - "fill": Scales to completely fill the canvas, center-cropping excess.
        - "fit": Scales image to fit inside canvas with clean borders (letterbox/pillarbox).
        - "none": Original 1:1 image placement without scaling.
        """
        if image.mode != "RGB":
            image = image.convert("RGB")

        spec = get_paper_spec(page_size_name)
        canvas_w = spec.get("width_600dpi", 2362)
        canvas_h = spec.get("height_600dpi", 3520)
        if dpi != 600:
            scale_factor = dpi / 600.0
            canvas_w = int(round(canvas_w * scale_factor))
            canvas_h = int(round(canvas_h * scale_factor))

        img_w, img_h = image.size

        # Auto-rotate to match paper orientation (Canon G640 feeds short edge first)
        if auto_rotate:
            is_canvas_portrait = canvas_h >= canvas_w
            is_img_portrait = img_h >= img_w
            if is_canvas_portrait != is_img_portrait:
                # Rotate 90 degrees clockwise to match canvas orientation
                image = image.rotate(-90, expand=True)
                img_w, img_h = image.size

        scale_x_factor = 1.0 + (scale_x_pct / 100.0)
        scale_y_factor = 1.0 + (scale_y_pct / 100.0)

        if fit_mode == "none":
            if scale_x_pct != 0.0 or scale_y_pct != 0.0:
                new_w = max(1, int(round(img_w * scale_x_factor)))
                new_h = max(1, int(round(img_h * scale_y_factor)))
                image = image.resize((new_w, new_h), resample=Image.Resampling.LANCZOS)
                img_w, img_h = image.size

            if img_w == canvas_w and img_h == canvas_h and offset_x_pct == 0.0 and offset_y_pct == 0.0:
                return image

            canvas = Image.new("RGB", (canvas_w, canvas_h), (255, 255, 255))
            shift_x = int(round((offset_x_pct / 100.0) * canvas_w))
            shift_y = int(round((offset_y_pct / 100.0) * canvas_h))
            paste_x = max(0, (canvas_w - img_w) // 2 + shift_x)
            paste_y = max(0, (canvas_h - img_h) // 2 + shift_y)
            canvas.paste(image, (paste_x, paste_y))
            return canvas

        if fit_mode == "compensate":
            # Hardware Bleed Compensation:
            # - Horizontal (width): Authentic photo covers 100% of canvas_w with calibrated hardware scaling.
            # - Vertical (height): Protects bottom from mechanical feed cut-off (comp_y_pct).
            shrink_h = float(np.clip(comp_y_pct / 100.0, 0.0, 0.20))
            safe_h = max(100, int(round(canvas_h * (1.0 - shrink_h))))

            # Uniform base scaling guaranteeing real photo covers full width and safe height
            base_scale = max(canvas_w / img_w, safe_h / img_h)
            inner_w = max(1, int(round(img_w * base_scale * scale_x_factor)))
            inner_h = max(1, int(round(img_h * base_scale * scale_y_factor)))

            inner_resized = image.resize((inner_w, inner_h), resample=Image.Resampling.LANCZOS)

            # Horizontal placement with offset
            shift_x = int(round((offset_x_pct / 100.0) * canvas_w))
            if inner_w >= canvas_w:
                base_crop_x = (inner_w - canvas_w) // 2
                crop_x = int(np.clip(base_crop_x + shift_x, 0, max(0, inner_w - canvas_w)))
                inner_w_cropped = inner_resized.crop((crop_x, 0, crop_x + canvas_w, inner_h))
            else:
                inner_w_cropped = Image.new("RGB", (canvas_w, inner_h), (255, 255, 255))
                pad_x = max(0, (canvas_w - inner_w) // 2 + shift_x)
                inner_w_cropped.paste(inner_resized, (pad_x, 0))

            # Vertical placement with offset
            shift_y = int(round((offset_y_pct / 100.0) * canvas_h))
            if inner_h >= safe_h:
                base_crop_y = max(0, inner_h - safe_h)
                crop_y = int(np.clip(base_crop_y + shift_y, 0, max(0, inner_h - safe_h)))
                inner_cropped = inner_w_cropped.crop((0, crop_y, canvas_w, crop_y + safe_h))
            else:
                inner_cropped = Image.new("RGB", (canvas_w, safe_h), (255, 255, 255))
                pad_y = max(0, safe_h - inner_h + shift_y)
                inner_cropped.paste(inner_w_cropped, (0, pad_y))

            # Build canvas: real photo fills columns 0..canvas_w and rows 0..safe_h
            canvas_arr = np.zeros((canvas_h, canvas_w, 3), dtype=np.uint8)
            canvas_arr[:safe_h, :] = np.array(inner_cropped, dtype=np.uint8)

            # Replicate bottom row ONLY into the printer's cut-off overspray zone (y >= safe_h)
            if safe_h < canvas_h:
                canvas_arr[safe_h:, :] = canvas_arr[safe_h - 1 : safe_h, :]

            return Image.fromarray(canvas_arr, mode="RGB")

        elif fit_mode == "fill":
            # Scale to completely fill canvas (crop excess)
            overspray = (bleed_pct / 100.0) if (borderless and bleed_pct > 0) else 0.0
            target_w = int(round(canvas_w * (1.0 + overspray)))
            target_h = int(round(canvas_h * (1.0 + overspray)))

            base_scale = max(target_w / img_w, target_h / img_h)
            new_w = max(1, int(round(img_w * base_scale * scale_x_factor)))
            new_h = max(1, int(round(img_h * base_scale * scale_y_factor)))

            resized = image.resize((new_w, new_h), resample=Image.Resampling.LANCZOS)
            base_crop_x = (new_w - canvas_w) // 2
            base_crop_y = (new_h - canvas_h) // 2
            shift_x = int(round((offset_x_pct / 100.0) * canvas_w))
            shift_y = int(round((offset_y_pct / 100.0) * canvas_h))
            crop_x = int(np.clip(base_crop_x + shift_x, 0, max(0, new_w - canvas_w)))
            crop_y = int(np.clip(base_crop_y + shift_y, 0, max(0, new_h - canvas_h)))
            framed = resized.crop((crop_x, crop_y, crop_x + canvas_w, crop_y + canvas_h))
            return framed

        elif fit_mode == "fit":
            # Scale to fit inside canvas (no cropping, letterbox/pillarbox)
            base_scale = min(canvas_w / img_w, canvas_h / img_h)
            new_w = max(1, int(round(img_w * base_scale * scale_x_factor)))
            new_h = max(1, int(round(img_h * base_scale * scale_y_factor)))

            resized = image.resize((new_w, new_h), resample=Image.Resampling.LANCZOS)
            canvas = Image.new("RGB", (canvas_w, canvas_h), (255, 255, 255))
            shift_x = int(round((offset_x_pct / 100.0) * canvas_w))
            shift_y = int(round((offset_y_pct / 100.0) * canvas_h))
            paste_x = max(0, (canvas_w - new_w) // 2 + shift_x)
            paste_y = max(0, (canvas_h - new_h) // 2 + shift_y)
            canvas.paste(resized, (paste_x, paste_y))
            return canvas

        return image

        return image

    @staticmethod
    def apply_contrast_curve(image: Image.Image, contrast: float = 0.0) -> Image.Image:
        """
        Apply photographic contrast boost using smooth symmetric sigmoid S-curve.
        y = x^gamma / (x^gamma + (1-x)^gamma)
        contrast = 0.0  -> gamma = 1.0 (identity / linear)
        contrast = 0.15 -> gamma = 1.15 (medium contrast punch)
        contrast = 0.25 -> gamma = 1.25 (high contrast / deep blacks)
        Preserves 0.0 (pure black), 1.0 (pure white), and 0.5 (midpoint) with zero clipping.
        """
        if abs(contrast) < 1e-4:
            return image
        if image.mode != "RGB":
            image = image.convert("RGB")
        arr = np.array(image, dtype=np.float32) / 255.0
        gamma = 1.0 + float(contrast)
        eps = 1e-5
        x = np.clip(arr, eps, 1.0 - eps)
        xg = x ** gamma
        yg = xg / (xg + (1.0 - x) ** gamma)
        out = np.clip(yg * 255.0 + 0.5, 0, 255).astype(np.uint8)
        return Image.fromarray(out, mode="RGB")

    def process_production_image(
        self,
        image: Image.Image,
        page_size_name: Optional[str] = None,
        borderless: bool = False,
        fit_mode: str = "compensate",
        bleed_pct: float = 0.0,
        comp_x_pct: float = 0.0,
        comp_y_pct: float = 5.0,
        offset_x_pct: float = 0.0,
        offset_y_pct: float = 0.0,
        scale_x_pct: float = 0.0,
        scale_y_pct: float = 0.0,
        contrast: Optional[float] = None,
        input_profile_override: Optional[LCMS2Profile] = None,
    ) -> Image.Image:
        """
        Mode 2: Production Mode.
        Full 16-bit precision color pipeline:
        1. Optional high-quality Lanczos scaling & framing for target paper size (borderless / bordered)
        2. High-precision 16-bit Contrast S-curve boost (preserves pure black & white without clipping)
        3. Input ICC -> Output Paper ICC transform (RelCol + BPC)
        4. 1D Channel Linearization LUT application
        5. Total Ink Limit (TIL) saturation limiting
        6. Quantization to 8-bit RGB for URF streaming
        """
        # Step 0: Layout & framing if page_size_name is requested
        if page_size_name is not None:
            image = self.prepare_image_layout(
                image,
                page_size_name=page_size_name,
                borderless=borderless,
                fit_mode=fit_mode,
                bleed_pct=bleed_pct,
                comp_x_pct=comp_x_pct,
                comp_y_pct=comp_y_pct,
                offset_x_pct=offset_x_pct,
                offset_y_pct=offset_y_pct,
                scale_x_pct=scale_x_pct,
                scale_y_pct=scale_y_pct,
            )

        # Step 1: Prepare 16-bit RGB buffer
        if image.mode != "RGB":
            image = image.convert("RGB")

        # Convert to 16-bit RGB numpy array [0..65535]
        arr_8 = np.array(image, dtype=np.uint8)
        # Scaled up to 16-bit: (x * 257) maps [0..255] exactly to [0..65535]
        arr_16 = (arr_8.astype(np.uint16) * 257)

        # Apply 16-bit Contrast S-Curve if enabled
        c_val = self.contrast if contrast is None else contrast
        if abs(c_val) >= 1e-4:
            gamma = 1.0 + float(c_val)
            eps = 1e-5
            x = np.clip(arr_16.astype(np.float32) / 65535.0, eps, 1.0 - eps)
            xg = x ** gamma
            arr_16 = np.clip((xg / (xg + (1.0 - x) ** gamma)) * 65535.0 + 0.5, 0, 65535).astype(np.uint16)

        # Step 2: LittleCMS2 ICC Transformation (if paper profile provided)
        out_16 = arr_16
        if self._paper_profile is not None:
            in_prof = input_profile_override or self._input_profile or LCMS2Profile.create_srgb()
            flags = cmsFLAGS_HIGHRESPRECALC
            if self.use_bpc:
                flags |= cmsFLAGS_BLACKPOINTCOMPENSATION

            transform = LCMS2Transform.create(
                input_profile=in_prof,
                in_format=TYPE_RGB_16,
                output_profile=self._paper_profile,
                out_format=TYPE_RGB_16,
                intent=self.intent,
                flags=flags,
            )
            out_16 = transform.transform(arr_16)

        # Step 3: Apply 1D Linearization LUT
        out_linearized_16 = self.linearization.apply(out_16)

        # Step 4: Apply Ink Limit (TIL)
        out_ink_limited_16 = self.ink_limiter.apply_rgb(out_linearized_16)

        # Step 5: Quantize from 16-bit to 8-bit RGB (with rounding)
        out_8 = np.clip((out_ink_limited_16.astype(np.float32) + 128.0) / 257.0, 0, 255).astype(np.uint8)

        return Image.fromarray(out_8, mode="RGB")

