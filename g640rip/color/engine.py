"""High-Level Color & Linearization Engine for Canon G640.

Implements:
1. Calibration Target Mode (Raw 1:1 Passthrough for ArgyllCMS targen/printtarg)
2. Production Mode (LittleCMS2 16-bit ICC + RelCol + BPC + 1D LUT Linearization + Total Ink Limit)
"""

import os
from typing import Optional, Tuple, Union
import numpy as np
from PIL import Image

from .ink_limit import InkLimiter
from .lcms2_capi import (
    LCMS2Profile,
    LCMS2Transform,
    TYPE_RGB_8,
    TYPE_RGB_16,
    INTENT_RELATIVE_COLORIMETRIC,
    INTENT_PERCEPTUAL,
    cmsFLAGS_BLACKPOINTCOMPENSATION,
    cmsFLAGS_HIGHRESPRECALC,
)
from .linearization import LinearizationLUT
from ..transport.constants import PAPER_SIZES


class ColorEngine:
    """Core color processing pipeline for Canon G640 micro-RIP."""

    def __init__(
        self,
        paper_profile_path: Optional[str] = None,
        input_profile_path: Optional[str] = None,
        linearization: Optional[LinearizationLUT] = None,
        ink_limiter: Optional[InkLimiter] = None,
        intent: int = INTENT_RELATIVE_COLORIMETRIC,
        use_bpc: bool = True,
    ):
        self.paper_profile_path = paper_profile_path
        self.input_profile_path = input_profile_path
        self.linearization = linearization or LinearizationLUT.create_identity()
        self.ink_limiter = ink_limiter or InkLimiter(max_total_ink=1.0)
        self.intent = intent
        self.use_bpc = use_bpc

        self._paper_profile: Optional[LCMS2Profile] = None
        self._input_profile: Optional[LCMS2Profile] = None

        if paper_profile_path and os.path.exists(paper_profile_path):
            self._paper_profile = LCMS2Profile.open_file(paper_profile_path)

        if input_profile_path and os.path.exists(input_profile_path):
            self._input_profile = LCMS2Profile.open_file(input_profile_path)

    # -------------------------------------------------------------
    # 1. Calibration Target Mode (ArgyllCMS Raw Passthrough)
    # -------------------------------------------------------------
    def process_calibration_target(
        self,
        target_image: Image.Image,
        page_size_name: str = "A4",
        dpi: int = 600,
        center_on_page: bool = True,
    ) -> Image.Image:
        """
        Mode 1: Calibration Target Mode.
        CRITICAL: Completely bypasses ICC profiles, ColorSync, and curves.
        Guarantees that RGB/CMYK patches generated by ArgyllCMS targen/printtarg
        are placed onto the 600 DPI canvas without ANY pixel interpolation,
        resampling, or color shifts.
        """
        # Ensure 8-bit RGB or convert cleanly without color management
        if target_image.mode != "RGB":
            target_image = target_image.convert("RGB")

        orig_w, orig_h = target_image.size
        target_arr = np.array(target_image, dtype=np.uint8)

        # Get canvas size
        page_spec = PAPER_SIZES.get(page_size_name, PAPER_SIZES["A4"])
        canvas_w = page_spec["width_600dpi"]
        canvas_h = page_spec["height_600dpi"]

        # If target already matches or exceeds canvas, do not resize patches
        if orig_w > canvas_w or orig_h > canvas_h:
            # Scale canvas up to target size so no patches are lost or resampled
            canvas_w = max(canvas_w, orig_w)
            canvas_h = max(canvas_h, orig_h)

        # Create pure white background (255, 255, 255)
        canvas = np.full((canvas_h, canvas_w, 3), 255, dtype=np.uint8)

        if center_on_page:
            offset_x = (canvas_w - orig_w) // 2
            offset_y = (canvas_h - orig_h) // 2
        else:
            offset_x = 0
            offset_y = 0

        # Direct 1:1 pixel copy - ZERO interpolation
        canvas[offset_y : offset_y + orig_h, offset_x : offset_x + orig_w] = target_arr

        return Image.fromarray(canvas, mode="RGB")

    # -------------------------------------------------------------
    # 2. Production Mode (16-bit ICC + Linearization + Ink Limit)
    # -------------------------------------------------------------
    def process_production_image(
        self,
        image: Image.Image,
        input_profile_override: Optional[LCMS2Profile] = None,
    ) -> Image.Image:
        """
        Mode 2: Production Mode.
        Full 16-bit precision color pipeline:
        1. Input ICC -> Output Paper ICC transform (RelCol + BPC)
        2. 1D Channel Linearization LUT application
        3. Total Ink Limit (TIL) saturation limiting
        4. Quantization to 8-bit RGB for URF streaming
        """
        # Step 1: Prepare 16-bit RGB buffer
        if image.mode != "RGB":
            image = image.convert("RGB")

        # Convert to 16-bit RGB numpy array [0..65535]
        arr_8 = np.array(image, dtype=np.uint8)
        # Scaled up to 16-bit: (x * 257) maps [0..255] exactly to [0..65535]
        arr_16 = (arr_8.astype(np.uint16) * 257)

        # Step 2: LittleCMS2 ICC Transformation (if paper profile provided)
        out_16 = arr_16
        if self._paper_profile is not None:
            in_prof = input_profile_override or self._input_profile or LCMS2Profile.create_srgb()
            flags = cmsFLAGS_HIGHRESPRECALC
            if self.use_bpc:
                flags |= cmsFLAGS_BLACKPOINTCOMPENSATION

            transform = LCMS2Transform.create(
                input_profile=in_prof,
                in_format=TYPE_RGB_16,
                output_profile=self._paper_profile,
                out_format=TYPE_RGB_16,
                intent=self.intent,
                flags=flags,
            )
            out_16 = transform.transform(arr_16)

        # Step 3: Apply 1D Linearization LUT
        out_linearized_16 = self.linearization.apply(out_16)

        # Step 4: Apply Ink Limit (TIL)
        out_ink_limited_16 = self.ink_limiter.apply_rgb(out_linearized_16)

        # Step 5: Quantize from 16-bit to 8-bit RGB (with rounding)
        out_8 = np.clip((out_ink_limited_16.astype(np.float32) + 128.0) / 257.0, 0, 255).astype(np.uint8)

        return Image.fromarray(out_8, mode="RGB")

